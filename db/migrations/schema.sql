                      ELSE m.before IS NOT NULL AND m.after IS NOT NULL AND m.before <> m.after END
                GROUP BY 2) t;
            RAISE NOTICE 'Migration 9d: % (%): % %', sign.name, sign.code, counted, change.name || detail;
        END LOOP;
    END LOOP;
