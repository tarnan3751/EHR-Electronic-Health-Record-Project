using Ehr.Data.Accounts;
using Ehr.Testing;
using Xunit;

namespace Ehr.Security.Tests;

// Supporting test for UC 6 (FR-30, FR-31), not one of the SE document's numbered test cases.
// Purpose / scenario: A patient tries to read another patient's test results. The results page takes no result or
//   patient ID, so the attempt is made where it would have to succeed: in the database, as the patient's session,
//   asking for the other patient's result by its ID and by that patient's ID. Row-level security returns zero rows.
// Type: Functional (invalid input)
// Requirements: see docs/UC6.md
// Use case: UC 6, View test results in the portal
// Preconditions: Two patients, each with a portal account and one released, final result. A clinician account exists.
// Inputs and system conditions: Queries on ehr.observations as each patient's account, with app.user_id set by
//   set_config as the first statement of the transaction, through both runtime roles: ehr_app (the on-site app) and
//   ehr_read (the cloud app).
// Test data: First patient's result: Hemoglobin A1c, status final, sampled and released Nov 2, 2026 15:00 UTC. Second
//   patient's result: Thyroid stimulating hormone, status final, sampled and released Nov 2, 2026 15:00 UTC. Patients
//   and accounts are generated by the test with random IDs.
// Steps:
//   1. Insert both results as the superuser, as the lab interface will.
//   2. Through ehr_app, as each patient, count their own result by ID, the other patient's result by ID, and the other
//      patient's results by patient ID, and list the patient IDs of every result the session can see; as the
//      clinician, count each result by ID.
//   3. Repeat step 2 through ehr_read.
// Expected result: Each patient counts 1 for their own result and 0 for the other patient's, by result ID and by
//   patient ID; every result each session can see is their own. The clinician counts 1 for each, so the rows exist.
// Creator: Simar Rekhi
public class PortalResultsIsolationTests(MigratedDatabase database) : IClassFixture<MigratedDatabase>
{
    string App => database.ConnectionStringFor("ehr_app", MigratedDatabase.AppPassword);

    string Read => database.ConnectionStringFor("ehr_read", MigratedDatabase.ReadPassword);

    [Fact]
    public async Task A_patient_cannot_read_another_patients_results()
    {
        var clinician = await Accounts.StaffAsync(database, StaffRoles.Clinician);
        var first = await Accounts.PatientAsync(database, clinician);
        var second = await Accounts.PatientAsync(database, clinician);
        var firstAccount = await Accounts.PatientAccountAsync(database, first);
        var secondAccount = await Accounts.PatientAccountAsync(database, second);
        var firstResult = await ReleasedResultAsync(first, "Hemoglobin A1c");
        var secondResult = await ReleasedResultAsync(second, "Thyroid stimulating hormone");

        const string byId = "SELECT count(*) FROM ehr.observations WHERE id = @id";
        const string byPatient = "SELECT count(*) FROM ehr.observations WHERE patient_id = @patient";
        const string patients = "SELECT DISTINCT patient_id FROM ehr.observations";
        foreach (var connectionString in new[] { App, Read })
        {
            Assert.Equal(["1"], await Accounts.QueryAsync(connectionString, firstAccount, byId, ("id", firstResult)));
            Assert.Equal(["0"], await Accounts.QueryAsync(connectionString, firstAccount, byId, ("id", secondResult)));
            Assert.Equal(["0"], await Accounts.QueryAsync(connectionString, firstAccount, byPatient, ("patient", second)));
            Assert.Equal([first.ToString()], await Accounts.QueryAsync(connectionString, firstAccount, patients));

            Assert.Equal(["1"], await Accounts.QueryAsync(connectionString, secondAccount, byId, ("id", secondResult)));
            Assert.Equal(["0"], await Accounts.QueryAsync(connectionString, secondAccount, byId, ("id", firstResult)));
            Assert.Equal(["0"], await Accounts.QueryAsync(connectionString, secondAccount, byPatient, ("patient", first)));
            Assert.Equal([second.ToString()], await Accounts.QueryAsync(connectionString, secondAccount, patients));

            // Both rows are there: the zeros above are the policy, not missing data.
            Assert.Equal(["1"], await Accounts.QueryAsync(connectionString, clinician, byId, ("id", firstResult)));
            Assert.Equal(["1"], await Accounts.QueryAsync(connectionString, clinician, byId, ("id", secondResult)));
        }
    }

    // Added with proxy access (FR-19; the expansion plan's step 6, Tahseen Arnan). The rule above used to be "a patient
    // sees only their own results". It is now "a portal session sees only the results of the one patient it is looking
    // at": its own, or, under a proxy grant that is the account's and in force, that patient's instead. So the same
    // attempt is made again by a proxy: with the grant, the other patient's released results and not their own or an
    // unreleased one; without it, or with someone else's, exactly what the test above shows.
    [Fact]
    public async Task A_proxy_reads_only_the_released_results_of_the_patient_they_act_for()
    {
        var clinician = await Accounts.StaffAsync(database, StaffRoles.Clinician);
        var patient = await Accounts.PatientAsync(database, clinician);
        var proxyPatient = await Accounts.PatientAsync(database, clinician);
        var third = await Accounts.PatientAsync(database, clinician);
        var patientAccount = await Accounts.PatientAccountAsync(database, patient);
        var proxyAccount = await Accounts.PatientAccountAsync(database, proxyPatient);
        var thirdAccount = await Accounts.PatientAccountAsync(database, third);
        var released = await ReleasedResultAsync(patient, "Hemoglobin A1c");
        var own = await ReleasedResultAsync(proxyPatient, "Thyroid stimulating hormone");
        var others = await ReleasedResultAsync(third, "Ferritin");
        var unreleased = Guid.CreateVersion7();
        await Accounts.ExecuteAsync(database.SuperuserConnectionString, null,
            "INSERT INTO ehr.observations (id, patient_id, display, status, effective_at) VALUES (@id, @patient, 'Potassium', 'final', now())",
            ("id", unreleased), ("patient", patient));
        var grant = Guid.CreateVersion7();
        await Accounts.ExecuteAsync(App, patientAccount,
            "INSERT INTO ehr.proxy_grants (id, patient_id, proxy_email, scope, include_sensitive, expires_at) VALUES (@id, @patient, @email, 'record', false, now() + interval '30 days')",
            ("id", grant), ("patient", patient), ("email", $"{proxyAccount:N}@example.com"));

        const string visible = "SELECT id FROM ehr.observations";
        foreach (var connectionString in new[] { App, Read })
        {
            Assert.Equal([own.ToString()], await Accounts.QueryAsync(connectionString, proxyAccount, visible));
            using (Accounts.ActingUnder(grant))
            {
                Assert.Equal([released.ToString()], await Accounts.QueryAsync(connectionString, proxyAccount, visible));
                // The grant is the proxy's alone: the third patient naming it sees nothing, not even their own.
                Assert.Empty(await Accounts.QueryAsync(connectionString, thirdAccount, visible));
            }

            Assert.Equal([others.ToString()], await Accounts.QueryAsync(connectionString, thirdAccount, visible));
        }
    }

    // A released, final result for the patient, inserted as the superuser the way the lab interface will.
    async Task<Guid> ReleasedResultAsync(Guid patient, string display)
    {
        var id = Guid.CreateVersion7();
        await Accounts.ExecuteAsync(database.SuperuserConnectionString, null,
            "INSERT INTO ehr.observations (id, patient_id, display, status, effective_at, issued_at) VALUES (@id, @patient, @display, 'final', '2026-11-02 15:00:00+00', '2026-11-02 15:00:00+00')",
            ("id", id), ("patient", patient), ("display", display));
        return id;
    }
}
