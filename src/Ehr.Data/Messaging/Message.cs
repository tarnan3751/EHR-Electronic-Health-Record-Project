using Ehr.Data.Patients;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Messaging;

// A conversation between a patient and their care team (FR-18): a subject and the messages under it. PHI: row-level
// security is enabled and forced on it and every write is recorded by trigger (db/policies); reads go through the PHI
// reader in Ehr.Domain, which records them. Started by the patient, in the portal, or by a clinician with the patient
// on their panel. Never edited or deleted. Synthetic data only.
public class MessageThread
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    public required string Subject { get; set; }

    // Set by the database.
    public DateTimeOffset StartedAt { get; set; }

    // When its latest message was sent, kept by the database: the lists show the latest first.
    public DateTimeOffset LastMessageAt { get; set; }
}

// One message of a thread, from the patient or from a staff member. PHI, like its thread. The database sets who sent
// it and when, and nothing changes it afterwards but the time the other side first read it. Never deleted.
public class Message
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid ThreadId { get; set; }

    // The thread's patient, repeated here for row-level security and the audit.
    public Guid PatientId { get; set; }

    // One of MessageSender.
    public required string SenderKind { get; set; }

    // The patient account or staff account that sent it, set by the database.
    public Guid SenderId { get; set; }

    public required string Body { get; set; }

    // Set by the database.
    public DateTimeOffset SentAt { get; set; }

    // When the other side first opened it: the patient for a staff message, a clinician for the patient's.
    public DateTimeOffset? ReadAt { get; set; }
}

public static class MessageSender
{
    public const string Patient = "patient";

    public const string Staff = "staff";

    public static readonly string[] All = [Patient, Staff];
}

// Maps ehr.message_threads and ehr.messages. EhrDbContext picks these up with ApplyConfigurationsFromAssembly.
public sealed class MessageThreadConfiguration : IEntityTypeConfiguration<MessageThread>
{
    public const int MaximumSubject = 150;

    public void Configure(EntityTypeBuilder<MessageThread> thread)
    {
        thread.ToTable("message_threads");
        thread.Property(t => t.Subject).HasMaxLength(MaximumSubject);
        thread.Property(t => t.StartedAt).HasDefaultValueSql("now()");
        thread.Property(t => t.LastMessageAt).HasDefaultValueSql("now()");
        thread.HasOne<Patient>().WithMany().HasForeignKey(t => t.PatientId).OnDelete(DeleteBehavior.Restrict);
        // A patient's threads, the latest first: the portal's and the chart's lists.
        thread.HasIndex(t => new { t.PatientId, t.LastMessageAt });
    }
}

public sealed class MessageConfiguration : IEntityTypeConfiguration<Message>
{
    public const int MaximumBody = 4000;

    public void Configure(EntityTypeBuilder<Message> message)
    {
        message.ToTable("messages", table =>
            table.HasCheckConstraint("ck_messages_sender_kind", $"sender_kind IN ({string.Join(", ", MessageSender.All.Select(kind => $"'{kind}'"))})"));
        message.Property(m => m.SenderKind).HasMaxLength(20);
        message.Property(m => m.Body).HasMaxLength(MaximumBody);
        message.Property(m => m.SenderId).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        message.Property(m => m.SentAt).HasDefaultValueSql("now()");
        message.HasOne<MessageThread>().WithMany().HasForeignKey(m => m.ThreadId).OnDelete(DeleteBehavior.Restrict);
        message.HasOne<Patient>().WithMany().HasForeignKey(m => m.PatientId).OnDelete(DeleteBehavior.Restrict);
        // A thread's messages in order.
        message.HasIndex(m => new { m.ThreadId, m.SentAt });
        // A patient's unread messages from their care team, which the portal's home counts on every visit: only the
        // unread ones are in it, so it stays small however many messages a patient has.
        // Named, beside the foreign key's own index on patient_id, which stays.
        message.HasIndex(m => m.PatientId, "ix_messages_patient_id");
        message.HasIndex(m => m.PatientId, "ix_messages_unread_from_staff").HasDatabaseName("ix_messages_unread_from_staff")
            .HasFilter($"sender_kind = '{MessageSender.Staff}' AND read_at IS NULL");
    }
}
