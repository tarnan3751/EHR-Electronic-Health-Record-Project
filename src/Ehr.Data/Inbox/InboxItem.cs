using Ehr.Data.Accounts;
using Ehr.Data.Patients;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Inbox;

// Something that needs a staff member's action: one row in their inbox. Each kind of item is added by the feature that
// creates it (a patient's message, a result to acknowledge, a refill request, an emergency access to review, a result
// no clinician can receive); the inbox itself only lists them, links each to its patient and source, and records when
// it was done. PHI, since an item names a patient: row-level security is enabled and forced on it and every write is
// recorded by trigger (db/policies); reads go through the PHI reader in Ehr.Domain. An item is seen by its recipient
// alone. Only the database's own triggers insert one, each kind's (db/policies), and nothing deletes one: done items
// stay. Synthetic data only.
public class InboxItem
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    // The staff account whose inbox it is in.
    public Guid RecipientId { get; set; }

    // One of InboxItemKind.
    public required string Kind { get; set; }

    // The patient it is about, when it is about one.
    public Guid? PatientId { get; set; }

    // What it is about: the table and row of the message, result, request or access.
    public string? SourceTable { get; set; }

    public Guid? SourceId { get; set; }

    // One line saying what needs doing, with no health details beyond what its kind implies.
    public required string Summary { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    // When the recipient marked it done, set by the database; null while it still needs action.
    public DateTimeOffset? DoneAt { get; set; }

    // Whether it is about a sensitive item, such as a pre-visit form's answer (step 13e): set by the database's own
    // trigger that creates it, so the write audit marks its events sensitive and the admin audit view shows none of
    // their values. Its summary never says more than its kind does.
    public bool Sensitive { get; set; }
}

// The kinds of item, each created by its own feature (docs/expansion/PLAN.md: steps 5, 7, 13d, 18 and 18a).
public static class InboxItemKind
{
    public const string Message = "message";

    public const string Result = "result";

    public const string RefillRequest = "refill-request";

    public const string EmergencyAccessReview = "emergency-access-review";

    // Someone else added an addendum to a note the recipient signed (step 10b).
    public const string Addendum = "addendum";

    // Someone else withdrew a visit summary the recipient released (step 13a).
    public const string SummaryWithdrawn = "summary-withdrawn";

    // A pre-visit form has an answer that needs review: a PHQ-9 question 9 answered other than "Not at all" (step 13e).
    public const string FormAlert = "form-alert";

    // A lab order's results arrived and no clinician can receive them: its signer can't, and nobody has the patient on
    // their panel. For each administrator, naming the patient by ID alone; done when a clinician acknowledges the
    // results (step 18a).
    public const string UnroutedResult = "unrouted-result";

    public static readonly string[] All = [Message, Result, RefillRequest, EmergencyAccessReview, Addendum, SummaryWithdrawn, FormAlert, UnroutedResult];

    // What the inbox calls each kind.
    public static readonly IReadOnlyDictionary<string, string> Names = new Dictionary<string, string>
    {
        [Message] = "Message",
        [Result] = "Result to acknowledge",
        [RefillRequest] = "Refill request",
        [EmergencyAccessReview] = "Break the glass to review",
        [Addendum] = "Addendum to your note",
        [SummaryWithdrawn] = "Visit summary withdrawn",
        [FormAlert] = "Pre-visit form to review",
        [UnroutedResult] = "Result with no clinician",
    };
}

// Maps ehr.inbox_items. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class InboxItemConfiguration : IEntityTypeConfiguration<InboxItem>
{
    public void Configure(EntityTypeBuilder<InboxItem> item)
    {
        item.ToTable("inbox_items", table =>
        {
            table.HasCheckConstraint("ck_inbox_items_kind", $"kind IN ({string.Join(", ", InboxItemKind.All.Select(kind => $"'{kind}'"))})");
            table.HasCheckConstraint("ck_inbox_items_source", "(source_table IS NULL) = (source_id IS NULL)");
            // An item about a pre-visit form's answer is a sensitive item's, always (step 13e).
            table.HasCheckConstraint("ck_inbox_items_form_alert_sensitive", $"kind <> '{InboxItemKind.FormAlert}' OR sensitive");
        });
        item.Property(i => i.Kind).HasMaxLength(40);
        item.Property(i => i.SourceTable).HasMaxLength(63);
        item.Property(i => i.Summary).HasMaxLength(300);
        item.HasOne<StaffUser>().WithMany().HasForeignKey(i => i.RecipientId).OnDelete(DeleteBehavior.Restrict);
        item.HasOne<Patient>().WithMany().HasForeignKey(i => i.PatientId).OnDelete(DeleteBehavior.Restrict);
        // What still needs action, oldest first: the inbox's list, and the count in the app bar on every clinical page.
        item.HasIndex(i => new { i.RecipientId, i.CreatedAt }).HasFilter("done_at IS NULL");
        // What was done, newest first.
        item.HasIndex(i => new { i.RecipientId, i.DoneAt }).HasFilter("done_at IS NOT NULL");
    }
}
