namespace Ehr.Data.Patients;

// A visit summary (the expansion plan's step 13a): what a clinician wrote for the patient from a signed note, in plain
// words, in three parts, and released to the patient portal. It is not the note: the note and its addenda never reach
// the portal, and a summary is written, never copied in. Released, its text is fixed: a wrong one is withdrawn, with a
// reason, and a new one written; a note has at most one standing summary. Its one other change is its sensitivity, as
// an addendum's: inherited from the note and its addenda, or marked on its own. The database sets who released it and
// when, takes the note's date, refuses internal codes and identifiers in it, and refuses any other change
// (db/policies/52-visit-summaries.sql). PHI: row-level security is enabled and forced on it and every write is recorded
// by trigger; reads go through the PHI reader. Synthetic data only.
public sealed class VisitSummary
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    // The signed note it was written from, and that note's patient; one foreign key over both.
    public Guid NoteId { get; set; }

    public Guid PatientId { get; set; }

    // "What we talked about", "What we found" and "What happens next": plain text, line breaks kept.
    public required string TalkedAbout { get; set; }

    public required string Found { get; set; }

    public required string NextSteps { get; set; }

    // When the note was signed, copied by the database: the date the portal shows, since the patient can't read the
    // note, and nothing links a note to a visit.
    public DateTimeOffset NoteSignedAt { get; set; }

    public Guid ReleasedBy { get; set; }

    public DateTimeOffset ReleasedAt { get; set; }

    // Sensitive (Tahseen's decision of 21 November 2026): because its note or one of the note's addenda is (inherited),
    // or marked so by a clinician, when it is released or afterwards. Shown in the portal to the patient, and to a
    // proxy only when the patient allows sensitive items.
    public bool Sensitive { get; set; }

    // Sensitive because the note or one of its addenda is, and for no other reason: set when the summary is released
    // from such a note, or when the note or an addendum becomes sensitive afterwards, and cleared when none of them is
    // sensitive any more. A summary marked on its own is not inherited, and stays marked until it is unmarked itself.
    // The database decides it.
    public bool SensitiveInherited { get; set; }

    // Who made it sensitive: whoever ticked "Sensitive" when releasing it, or marked it afterwards. Null while it isn't
    // sensitive, and for an inherited mark. Only that person, or the note's signer, unmarks it.
    public Guid? SensitiveMarkedBy { get; set; }

    // Why its sensitivity last changed after it was released, and when. Null if it never changed.
    public string? SensitiveReason { get; set; }

    public DateTimeOffset? SensitiveChangedAt { get; set; }

    // Withdrawn: no longer shown in the portal, kept in the record with who, when and why. Null while it stands.
    public DateTimeOffset? WithdrawnAt { get; set; }

    public Guid? WithdrawnBy { get; set; }

    public string? WithdrawnReason { get; set; }
}
