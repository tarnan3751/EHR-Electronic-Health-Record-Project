namespace Ehr.Data.Patients;

// A test result or a vital sign, shaped on FHIR's Observation (the laboratory and vital-signs categories): one measured
// value, its unit and the range that is normal for it. Patients see their own in the portal once it is released (UC6,
// FR-16; Simar Rekhi). PHI: row-level security is enabled and forced on it, and every write is recorded by trigger
// (db/policies); reads go through the PHI reader in Ehr.Domain, which records them. A clinician files an order's results
// and records vital signs (Ehr.Domain.Results); a trigger decides what each row may hold (db/policies/75-results.sql).
// Nothing updates or deletes one. Synthetic data only.
public class Observation
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // The lab order this result answers (UC 1), when there is one; it must be the same patient's.
    public Guid? OrderId { get; set; }

    // One of ObservationCategory: a laboratory result, or a vital sign (the expansion plan's step 9).
    public string Category { get; set; } = ObservationCategory.Laboratory;

    // The visit a vital sign was taken at, when it was taken at one.
    public Guid? EncounterId { get; set; }

    // A vital sign marked "entered in error" (the expansion plan's step 9b): why, by whom and when. The row is never
    // deleted; its Status becomes ObservationStatus.EnteredInError, and the correct value is a new reading. The
    // database sets who and when (db/policies/75-results.sql).
    public string? EnteredInErrorReason { get; set; }

    public Guid? EnteredInErrorBy { get; set; }

    public DateTimeOffset? EnteredInErrorAt { get; set; }

    // The test as a LOINC code, such as 4548-4 for hemoglobin A1c, when it has one.
    public string? Code { get; set; }

    // The test as people read it, such as "Hemoglobin A1c".
    public required string Display { get; set; }

    // One of ObservationStatus.
    public required string Status { get; set; }

    // The measured value and its unit, such as 6.9 and "%".
    public decimal? Value { get; set; }

    public string? Unit { get; set; }

    // The normal range, in the same unit. Either end may be missing, as in "below 100".
    public decimal? ReferenceLow { get; set; }

    public decimal? ReferenceHigh { get; set; }

    // When the sample was taken.
    public DateTimeOffset EffectiveAt { get; set; }

    // When the result was released. Until then only clinicians see it: row-level security hides it from the patient.
    public DateTimeOffset? IssuedAt { get; set; }

    // What the clinician wants the patient to know about it, such as "We'll talk about this at your next visit."
    public string? Note { get; set; }
}

// FHIR's observation categories, the two this system records.
public static class ObservationCategory
{
    public const string Laboratory = "laboratory";

    public const string VitalSigns = "vital-signs";

    public static readonly string[] All = [Laboratory, VitalSigns];
}

// The vital signs recorded (step 9), by LOINC code, as db/reference loads them into ehr.observation_codes.
public static class VitalSign
{
    public const string Systolic = "8480-6";
    public const string Diastolic = "8462-4";
    public const string HeartRate = "8867-4";
    public const string Temperature = "8310-5";
    public const string RespiratoryRate = "9279-1";
    public const string OxygenSaturation = "59408-5";
    public const string Weight = "29463-7";
    public const string Height = "8302-2";
    public const string BodyMassIndex = "39156-5";

    // In the order a flowsheet lists them.
    public static readonly string[] All = [Systolic, Diastolic, HeartRate, Temperature, RespiratoryRate, OxygenSaturation, Weight, Height, BodyMassIndex];
}

// FHIR R4's Observation status codes, the values Observation.Status may hold.
public static class ObservationStatus
{
    public const string Registered = "registered";

    public const string Preliminary = "preliminary";

    public const string Final = "final";

    public const string Amended = "amended";

    public const string Corrected = "corrected";

    public const string Cancelled = "cancelled";

    public const string EnteredInError = "entered-in-error";

    public static readonly string[] All = [Registered, Preliminary, Final, Amended, Corrected, Cancelled, EnteredInError];

    // The ones a patient may see once released: a finished result, or one changed after it was finished.
    public static readonly string[] Released = [Final, Amended, Corrected];
}
