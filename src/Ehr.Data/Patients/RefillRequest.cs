namespace Ehr.Data.Patients;

// A refill request (the expansion plan's step 13d): the patient, or someone they share their record with whose access
// includes messages, asking the care team in the portal to renew a medication on the chart. Shaped on FHIR's Task, a
// request for someone to act, with its status codes. It goes to the inbox of each clinician with the patient on their
// panel; one of them answers it once: approves it by signing an order for the same medication through the order form,
// in the same transaction, or declines it with a message for the patient. The database decides who may ask about which
// medication and who may answer, sets who asked and answered and when, copies the medication's name and sensitivity,
// keeps one open request a medication, delivers and clears the inbox items, and refuses every other change and every
// delete (db/policies/77-refill-requests.sql). PHI: row-level security is enabled and forced on it and every write is
// recorded by trigger; reads go through the PHI reader. Synthetic data only.
public sealed class RefillRequest
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // The medication on the chart that was asked for.
    public Guid MedicationStatementId { get; set; }

    // The medication's name when it was asked for, copied by the database: what the patient's list says was asked,
    // whatever later becomes of the medication's entry.
    public string MedicationDisplay { get; set; } = "";

    // What the patient added, optional: plain text, line breaks kept.
    public string? Note { get; set; }

    // The portal account that asked, the patient's own or a proxy's, and when: the database's.
    public Guid RequestedBy { get; set; }

    public DateTimeOffset RequestedAt { get; set; }

    // One of RefillRequestStatus: requested until it is answered.
    public required string Status { get; set; }

    // Approved: the order signed for it, and the name of what was ordered, which the database copies from the catalog.
    public Guid? OrderId { get; set; }

    public string? OrderedDisplay { get; set; }

    // Declined: the clinician's message to the patient.
    public string? DeclineMessage { get; set; }

    // Who answered it and when: the database's. Null while it waits.
    public Guid? DecidedBy { get; set; }

    public DateTimeOffset? DecidedAt { get; set; }

    // The medication's own mark, which the database copies and keeps in step with it: a request for a sensitive
    // medication is a sensitive item.
    public bool Sensitive { get; set; }
}

// FHIR R4's Task status codes that a refill request takes: requested while it waits, completed once approved, rejected
// once declined. The pages call them waiting, approved and declined.
public static class RefillRequestStatus
{
    public const string Requested = "requested";

    public const string Completed = "completed";

    public const string Rejected = "rejected";

    public static readonly string[] All = [Requested, Completed, Rejected];
}
