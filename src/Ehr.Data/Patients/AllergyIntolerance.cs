namespace Ehr.Data.Patients;

// An allergy or intolerance on a patient's chart, shaped on FHIR's AllergyIntolerance. PHI: row-level security is
// enabled and forced on it and every write is recorded by trigger (db/policies); reads go through the PHI reader in
// Ehr.Domain, which records them. Clinicians with the patient on their panel add and change entries, and mark them
// inactive; nothing deletes one, and every change is kept in ehr.chart_history. "No known allergies" is a row too, as
// FHIR records it, with the app's own code NoKnownAllergy, so a chart can tell it apart from having no allergy
// information at all. Synthetic data only.
public class AllergyIntolerance
{
    // The app's own marker for "No known allergy": no licensed code system is used (the plan allows no SNOMED CT). The
    // AllergyCodes migration rewrote the SNOMED CT code this replaced.
    public const string NoKnownAllergy = "no-known-allergy";

    // Its name, as stored and shown. Entries recorded before this wording say "No known allergy"; the app shows every
    // such entry by its code with this name (ChartLists.DisplayOf).
    public const string NoKnownAllergyDisplay = "No known allergies";

    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // The substance's code, when it has one, and the system the code is from: an RxNorm ingredient for a drug, an FDA
    // UNII substance for a food or the like (ClinicalCodeSystem). NoKnownAllergy is the app's own and has no system.
    public string? Code { get; set; }

    public string? CodeSystem { get; set; }

    // The substance as clinicians read it, such as "Penicillin".
    public required string Display { get; set; }

    // One of AllergyClinicalStatus.
    public required string ClinicalStatus { get; set; }

    // One of AllergyCategory, when known.
    public string? Category { get; set; }

    // One of AllergyCriticality, when assessed.
    public string? Criticality { get; set; }

    // What the patient has when exposed, such as "Hives", and how bad it was: one of AllergySeverity, when known.
    public string? Reaction { get; set; }

    public string? Severity { get; set; }

    public DateTimeOffset RecordedAt { get; set; }
}

// FHIR's allergy clinical status codes, the values AllergyIntolerance.ClinicalStatus may hold.
public static class AllergyClinicalStatus
{
    public const string Active = "active";

    public const string Inactive = "inactive";

    public const string Resolved = "resolved";

    public static readonly string[] All = [Active, Inactive, Resolved];
}

// FHIR's allergy category codes.
public static class AllergyCategory
{
    public const string Food = "food";

    public const string Medication = "medication";

    public const string Environment = "environment";

    public const string Biologic = "biologic";

    public static readonly string[] All = [Food, Medication, Environment, Biologic];
}

// FHIR's reaction severity codes.
public static class AllergySeverity
{
    public const string Mild = "mild";

    public const string Moderate = "moderate";

    public const string Severe = "severe";

    public static readonly string[] All = [Mild, Moderate, Severe];
}

// FHIR's allergy criticality codes.
public static class AllergyCriticality
{
    public const string Low = "low";

    public const string High = "high";

    public const string UnableToAssess = "unable-to-assess";

    public static readonly string[] All = [Low, High, UnableToAssess];
}
