using Ehr.Data.Accounts;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Patients;

// A clinician's confirmation that everyone who would speak at a visit agreed aloud to its conversation being recorded
// to draft the note (ambient listening, the expansion plan's step 16; UC 23). Written before any audio is captured, and
// named by the one review of a conversation it allows (AiNoteReview.ConsentId). Never changed or deleted. The database
// sets the clinician and the time (db/policies/56-ambient-listening.sql), and its write audit is the consent's record in
// the audit log: who, which patient, when, how many people would speak and who agreed. No names and no text. PHI:
// row-level security is enabled and forced on it, and reads go through the PHI reader. Synthetic data only.
public sealed class AmbientConsent
{
    // UUIDv7, generated by the app.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // The clinician who confirmed it: always the signed-in one.
    public Guid ClinicianId { get; set; }

    // How many people would speak: the patient and the clinician (2), or one more, such as a relative (3).
    public short Speakers { get; set; }

    // Who agreed for the patient (AmbientConsentGivers).
    public required string GivenBy { get; set; }

    // When, on the database's clock.
    public DateTimeOffset ConfirmedAt { get; set; }
}

public static class AmbientConsentGivers
{
    public const string Patient = "patient";

    // Someone who decides for the patient: a parent or guardian, or a legal representative.
    public const string Representative = "representative";
}

// Maps ehr.ambient_consents. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class AmbientConsentConfiguration : IEntityTypeConfiguration<AmbientConsent>
{
    public void Configure(EntityTypeBuilder<AmbientConsent> consent)
    {
        consent.ToTable("ambient_consents", table =>
        {
            table.HasCheckConstraint("ck_ambient_consents_speakers", "speakers IN (2, 3)");
            table.HasCheckConstraint("ck_ambient_consents_given_by", "given_by IN ('patient', 'representative')");
        });
        consent.HasAlternateKey(c => new { c.Id, c.PatientId });
        consent.Property(c => c.GivenBy).HasMaxLength(16);
        consent.Property(c => c.ClinicianId).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        consent.Property(c => c.ConfirmedAt).HasDefaultValueSql("now()");
        consent.HasOne<Patient>().WithMany().HasForeignKey(c => c.PatientId).OnDelete(DeleteBehavior.Restrict);
        consent.HasOne<StaffUser>().WithMany().HasForeignKey(c => c.ClinicianId).OnDelete(DeleteBehavior.Restrict);
    }
}
