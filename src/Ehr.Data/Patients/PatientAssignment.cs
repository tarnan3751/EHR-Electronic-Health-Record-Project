namespace Ehr.Data.Patients;

// A patient on a clinician's panel: the patients a clinician sees first, before searching. PHI, because the row says
// who a patient's clinician is: row-level security is enabled and forced on it and every write is recorded by trigger
// (db/policies). An assignment ends rather than being deleted (EndedAt), so the panel's history stays and the patient
// can be assigned again later. Access to a chart never depends on it: a clinician may open any patient's chart, and
// one not on their panel asks for a reason first (Ehr.Domain.Patients.BreakGlass).
public class PatientAssignment
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // The staff account the patient is assigned to.
    public Guid ClinicianId { get; set; }

    public DateTimeOffset AssignedAt { get; set; }

    // Set when the assignment ends; null while it stands.
    public DateTimeOffset? EndedAt { get; set; }
}
