namespace Ehr.Data.Accounts;

// A desktop app signed in as a staff account: the SHA-256 of the token the app holds, which account, which device, and
// until when. The app sends the token with every sync request (Api/Sync), and the Desktop authentication scheme looks
// the session up by its hash. Not PHI, and not under row-level security: the lookup happens before anyone is signed
// in, like the account tables (db/policies/10-grants.sql). A session ends by expiring, by sign-out (RevokedAt), or when
// the account's security stamp changes, as at a password change.
public class DesktopSession
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid StaffUserId { get; set; }

    // Hex SHA-256 of the token. The token itself is never stored.
    public required string TokenHash { get; set; }

    // The account's security stamp when the session began; a different one now means the session is over.
    public required string SecurityStamp { get; set; }

    // What the app called the device, such as "macos desktop".
    public required string Device { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    public DateTimeOffset ExpiresAt { get; set; }

    public DateTimeOffset? RevokedAt { get; set; }
}
