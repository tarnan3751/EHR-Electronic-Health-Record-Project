using Ehr.Data.Accounts;
using Ehr.Data.Patients;
using Ehr.Data.Proxies;
using Ehr.Data.Reference;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Forms;

// A pre-visit form's answers (the expansion plan's step 13e), sent once from the portal by the patient or by a proxy
// the patient allowed sensitive items. A record: never changed or deleted, by anyone. The database scores it from the
// answers and the request's copy of the questionnaire, whatever the client sent, and sets who answered, under which
// proxy grant, and when (db/policies/85-pre-visit-forms.sql). An answer that needs review puts an item in the care
// team's inbox. A sensitive item always. PHI: row-level security is enabled and forced on it and every write is
// recorded by trigger; reads go through the PHI reader. Synthetic data only.
public sealed class QuestionnaireResponse
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    // The request it answers: once.
    public Guid RequestId { get; set; }

    // Copied from the request by the database.
    public Guid PatientId { get; set; }

    public required string QuestionnaireCode { get; set; }

    public Guid ClinicianId { get; set; }

    // JSON: each question's LOINC code and the LOINC code of the answer chosen.
    public required string Answers { get; set; }

    // Worked out by the database: the total, its severity band, whether it needs follow-up, and whether an answer
    // needs review (a PHQ-9 question 9 answered other than "Not at all").
    public int? Score { get; set; }

    public string? Band { get; set; }

    public bool FollowUp { get; set; }

    public bool Alert { get; set; }

    // The portal account that sent it: the patient's own, or a proxy's under ProxyGrantId.
    public Guid AnsweredBy { get; set; }

    public Guid? ProxyGrantId { get; set; }

    public DateTimeOffset AnsweredAt { get; set; }

    // Always true, and can't be anything else.
    public bool Sensitive { get; set; } = true;
}

// Maps ehr.questionnaire_responses. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class QuestionnaireResponseConfiguration : IEntityTypeConfiguration<QuestionnaireResponse>
{
    public void Configure(EntityTypeBuilder<QuestionnaireResponse> response)
    {
        response.ToTable("questionnaire_responses", table =>
        {
            table.HasCheckConstraint("ck_questionnaire_responses_sensitive", "sensitive");
            table.HasCheckConstraint("ck_questionnaire_responses_answers", "jsonb_typeof(answers) = 'object'");
            table.HasCheckConstraint("ck_questionnaire_responses_score", "score >= 0");
        });
        response.Property(r => r.QuestionnaireCode).HasMaxLength(20);
        response.Property(r => r.Answers).HasColumnType("jsonb");
        response.Property(r => r.Band).HasMaxLength(60);
        response.Property(r => r.AnsweredBy).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        response.Property(r => r.AnsweredAt).HasDefaultValueSql("now()");
        response.HasOne<QuestionnaireRequest>().WithOne().HasForeignKey<QuestionnaireResponse>(r => r.RequestId).OnDelete(DeleteBehavior.Restrict);
        response.HasOne<Patient>().WithMany().HasForeignKey(r => r.PatientId).OnDelete(DeleteBehavior.Restrict);
        response.HasOne<Questionnaire>().WithMany().HasForeignKey(r => r.QuestionnaireCode).OnDelete(DeleteBehavior.Restrict);
        response.HasOne<StaffUser>().WithMany().HasForeignKey(r => r.ClinicianId).OnDelete(DeleteBehavior.Restrict);
        response.HasOne<PatientUser>().WithMany().HasForeignKey(r => r.AnsweredBy).OnDelete(DeleteBehavior.Restrict);
        response.HasOne<ProxyGrant>().WithMany().HasForeignKey(r => r.ProxyGrantId).OnDelete(DeleteBehavior.Restrict);
        // A patient's answers, newest first: the forms page and the trend.
        response.HasIndex(r => new { r.PatientId, r.AnsweredAt });
    }
}
