using Ehr.Data.Accounts;
using Ehr.Data.Patients;
using Ehr.Data.Reference;
using Ehr.Data.Scheduling;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Forms;

// A pre-visit form (the expansion plan's step 13e): a clinician's request that the patient fill in a questionnaire
// before a booked appointment. It keeps a copy of the questionnaire's definition as it was asked, which the patient
// answers and the database scores, so a later change to the reference data never rewrites what someone answered.
// Never changed or deleted, by anyone. The database sets the patient and the clinician from the appointment, who asked
// and when, and the copy (db/policies/85-pre-visit-forms.sql). A sensitive item always: a request names the
// questionnaire, which says something of what the clinician is looking for. PHI: row-level security is enabled and
// forced on it and every write is recorded by trigger; reads go through the PHI reader. Synthetic data only.
public sealed class QuestionnaireRequest
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    public Guid AppointmentId { get; set; }

    // The clinician the patient is booked with: who is told when an answer needs review.
    public Guid ClinicianId { get; set; }

    // The questionnaire (Ehr.Data.Reference.Questionnaire), by its LOINC panel code.
    public required string QuestionnaireCode { get; set; }

    // The questionnaire's definition as it was when asked: JSON, the shape db/reference/36-questionnaires.sql describes.
    public string Definition { get; set; } = "{}";

    public Guid RequestedBy { get; set; }

    public DateTimeOffset RequestedAt { get; set; }

    // Always true, and can't be anything else.
    public bool Sensitive { get; set; } = true;
}

// Maps ehr.questionnaire_requests. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class QuestionnaireRequestConfiguration : IEntityTypeConfiguration<QuestionnaireRequest>
{
    public void Configure(EntityTypeBuilder<QuestionnaireRequest> request)
    {
        request.ToTable("questionnaire_requests", table =>
        {
            table.HasCheckConstraint("ck_questionnaire_requests_sensitive", "sensitive");
            table.HasCheckConstraint("ck_questionnaire_requests_definition", "jsonb_typeof(definition) = 'object'");
        });
        request.Property(r => r.QuestionnaireCode).HasMaxLength(20);
        request.Property(r => r.Definition).HasColumnType("jsonb");
        request.Property(r => r.RequestedBy).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        request.Property(r => r.RequestedAt).HasDefaultValueSql("now()");
        request.HasOne<Patient>().WithMany().HasForeignKey(r => r.PatientId).OnDelete(DeleteBehavior.Restrict);
        request.HasOne<Appointment>().WithMany().HasForeignKey(r => r.AppointmentId).OnDelete(DeleteBehavior.Restrict);
        request.HasOne<StaffUser>().WithMany().HasForeignKey(r => r.ClinicianId).OnDelete(DeleteBehavior.Restrict);
        request.HasOne<StaffUser>().WithMany().HasForeignKey(r => r.RequestedBy).OnDelete(DeleteBehavior.Restrict);
        // A questionnaire that has been asked for can't be removed from the reference data.
        request.HasOne<Questionnaire>().WithMany().HasForeignKey(r => r.QuestionnaireCode).OnDelete(DeleteBehavior.Restrict);
        // Each questionnaire once for an appointment.
        request.HasIndex(r => new { r.AppointmentId, r.QuestionnaireCode }).IsUnique();
        // A patient's forms, and the chart's count of them.
        request.HasIndex(r => new { r.PatientId, r.RequestedAt });
    }
}
