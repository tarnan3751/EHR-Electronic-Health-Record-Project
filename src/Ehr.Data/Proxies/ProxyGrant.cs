using Ehr.Data.Patients;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Proxies;

// One person's permission to use the portal for a patient (FR-19): a parent for a child, a carer for a relative. PHI:
// row-level security is enabled and forced on it and every write is recorded by trigger (db/policies); reads go
// through the PHI reader in Ehr.Domain. Given by the patient, in the portal, or recorded by a clinician with the
// patient on their panel. It names the proxy by the email of their portal account, has a scope and always an expiry,
// and ends early when it is revoked. The database decides what it lets the proxy see (db/policies/30-rls.sql).
// Never deleted. Synthetic data only.
public class ProxyGrant
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    // Whose record it opens.
    public Guid PatientId { get; set; }

    // The proxy's portal email, upper-cased as ASP.NET Core Identity normalizes it. The grant works for the confirmed
    // account with that email, and says nothing about whether one exists.
    public required string ProxyEmail { get; set; }

    // One of ProxyScope.
    public required string Scope { get; set; }

    // Whether the proxy also sees items marked sensitive. Only the patient can turn it on.
    public bool IncludeSensitive { get; set; }

    // "patient" or "staff", and the account: set by the database.
    public string GrantedByKind { get; set; } = "";

    public Guid GrantedBy { get; set; }

    public DateTimeOffset GrantedAt { get; set; }

    public DateTimeOffset ExpiresAt { get; set; }

    // Set by the database when it is revoked, with who did it.
    public DateTimeOffset? RevokedAt { get; set; }

    public Guid? RevokedBy { get; set; }
}

public static class ProxyScope
{
    // The record, results and appointments, to read.
    public const string Record = "record";

    // That, and reading and sending the patient's messages.
    public const string RecordAndMessages = "record-and-messages";

    public static readonly string[] All = [Record, RecordAndMessages];
}

// Maps ehr.proxy_grants. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class ProxyGrantConfiguration : IEntityTypeConfiguration<ProxyGrant>
{
    public const int MaximumEmail = 256;

    public void Configure(EntityTypeBuilder<ProxyGrant> grant)
    {
        grant.ToTable("proxy_grants", table =>
        {
            table.HasCheckConstraint("ck_proxy_grants_scope", $"scope IN ({string.Join(", ", ProxyScope.All.Select(scope => $"'{scope}'"))})");
            table.HasCheckConstraint("ck_proxy_grants_granted_by_kind", "granted_by_kind IN ('patient', 'staff')");
        });
        grant.Property(g => g.ProxyEmail).HasMaxLength(MaximumEmail);
        grant.Property(g => g.Scope).HasMaxLength(30);
        grant.Property(g => g.GrantedByKind).HasMaxLength(20).HasDefaultValue("patient");
        grant.Property(g => g.GrantedBy).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        grant.Property(g => g.GrantedAt).HasDefaultValueSql("now()");
        grant.HasOne<Patient>().WithMany().HasForeignKey(g => g.PatientId).OnDelete(DeleteBehavior.Restrict);

        // One grant that hasn't been revoked per patient and proxy: giving it again replaces it.
        grant.HasIndex(g => new { g.PatientId, g.ProxyEmail }).IsUnique().HasFilter("revoked_at IS NULL");

        // The grants addressed to one account: whose records it may open.
        grant.HasIndex(g => g.ProxyEmail);
    }
}
