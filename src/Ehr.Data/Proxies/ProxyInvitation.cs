using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Proxies;

// A single-use, expiring invitation to create a proxy-only portal account (the expansion plan's step 6b), sent to the
// address a proxy grant names. Only the code's hash is stored. Internal, like portal enrollment codes: grants and no
// row-level security, because the invitation is looked up before anyone is signed in. It opens nothing by itself: the
// account it creates sees only what grants addressed to its email allow.
public class ProxyInvitation
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    // The grant it was sent for.
    public Guid GrantId { get; set; }

    // The address it was sent to, as the grant holds it: the account is created with this address and no other.
    public required string Email { get; set; }

    // SHA-256 of the code in the link, in hex.
    public required string CodeHash { get; set; }

    public DateTimeOffset IssuedAt { get; set; }

    public DateTimeOffset ExpiresAt { get; set; }

    // Set when an account was created with it: it never works again.
    public DateTimeOffset? RedeemedAt { get; set; }
}

// Maps ehr.proxy_invitations. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class ProxyInvitationConfiguration : IEntityTypeConfiguration<ProxyInvitation>
{
    public void Configure(EntityTypeBuilder<ProxyInvitation> invitation)
    {
        invitation.ToTable("proxy_invitations");
        invitation.Property(i => i.Email).HasMaxLength(ProxyGrantConfiguration.MaximumEmail);
        invitation.Property(i => i.CodeHash).HasMaxLength(64);
        invitation.Property(i => i.IssuedAt).HasDefaultValueSql("now()");
        invitation.HasIndex(i => i.CodeHash).IsUnique();
        invitation.HasIndex(i => i.GrantId);
        invitation.HasOne<ProxyGrant>().WithMany().HasForeignKey(i => i.GrantId).OnDelete(DeleteBehavior.Restrict);
    }
}
