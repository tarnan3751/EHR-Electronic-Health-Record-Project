using Ehr.Data.Accounts;
using Ehr.Data.Patients;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Scheduling;

// A time a patient is booked to see a clinician, shaped on FHIR's Appointment (FR-17). PHI: row-level security is
// enabled and forced on it and every write is recorded by trigger (db/policies); reads go through the PHI reader in
// Ehr.Domain. Clinicians book, reschedule and cancel for a patient on their panel; a patient sees their own in the
// portal. Never deleted: a cancelled appointment stays, with its reason. When the patient arrives, checking in creates
// the visit (an Encounter) and links it here. Times are UTC. Synthetic data only.
public class Appointment
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // The clinician the patient is booked with.
    public Guid ClinicianId { get; set; }

    public DateTimeOffset StartsAt { get; set; }

    // How long it is booked for.
    public int Minutes { get; set; }

    // Why the patient is coming, such as "Blood pressure check": what the patient sees too.
    public required string Reason { get; set; }

    // One of AppointmentStatus.
    public required string Status { get; set; }

    // Why it was cancelled; null otherwise.
    public string? CancelReason { get; set; }

    // The visit it became, once the patient was checked in.
    public Guid? EncounterId { get; set; }

    // Who booked it and when, set by the database.
    public Guid BookedById { get; set; }

    public DateTimeOffset BookedAt { get; set; }

    // Counts the appointment's changes, kept by the database. A change says which version it started from, and is
    // refused when the appointment has moved on since: so a page opened before a colleague rescheduled can't quietly
    // put the old time back.
    public int Version { get; set; }
}

// FHIR R4's appointment status codes that this clinic uses.
public static class AppointmentStatus
{
    public const string Booked = "booked";

    public const string Cancelled = "cancelled";

    // The patient came: there is a visit.
    public const string Fulfilled = "fulfilled";

    public const string NoShow = "noshow";

    public static readonly string[] All = [Booked, Cancelled, Fulfilled, NoShow];

    // What the screens call each.
    public static readonly IReadOnlyDictionary<string, string> Names = new Dictionary<string, string>
    {
        [Booked] = "Booked",
        [Cancelled] = "Cancelled",
        [Fulfilled] = "Checked in",
        [NoShow] = "No-show",
    };
}

// Maps ehr.appointments. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class AppointmentConfiguration : IEntityTypeConfiguration<Appointment>
{
    // The lengths a booking may have.
    public const int ShortestMinutes = 5;

    public const int LongestMinutes = 240;

    public void Configure(EntityTypeBuilder<Appointment> appointment)
    {
        appointment.ToTable("appointments", table =>
        {
            table.HasCheckConstraint("ck_appointments_status", $"status IN ({string.Join(", ", AppointmentStatus.All.Select(status => $"'{status}'"))})");
            table.HasCheckConstraint("ck_appointments_minutes", $"minutes BETWEEN {ShortestMinutes} AND {LongestMinutes}");
            table.HasCheckConstraint("ck_appointments_cancelled", $"(status = '{AppointmentStatus.Cancelled}') = (cancel_reason IS NOT NULL)");
            table.HasCheckConstraint("ck_appointments_visit", $"(status = '{AppointmentStatus.Fulfilled}') = (encounter_id IS NOT NULL)");
        });
        appointment.Property(a => a.Reason).HasMaxLength(200);
        appointment.Property(a => a.Status).HasMaxLength(20);
        appointment.Property(a => a.CancelReason).HasMaxLength(500);
        appointment.Property(a => a.BookedById).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        appointment.Property(a => a.BookedAt).HasDefaultValueSql("now()");
        appointment.Property(a => a.Version).HasDefaultValue(1).IsConcurrencyToken();
        appointment.HasOne<Patient>().WithMany().HasForeignKey(a => a.PatientId).OnDelete(DeleteBehavior.Restrict);
        appointment.HasOne<StaffUser>().WithMany().HasForeignKey(a => a.ClinicianId).OnDelete(DeleteBehavior.Restrict);
        appointment.HasOne<StaffUser>().WithMany().HasForeignKey(a => a.BookedById).OnDelete(DeleteBehavior.Restrict);
        appointment.HasOne<Encounter>().WithOne().HasForeignKey<Appointment>(a => a.EncounterId).OnDelete(DeleteBehavior.Restrict);
        // A clinician's day, and the check for a booking that overlaps another.
        appointment.HasIndex(a => new { a.ClinicianId, a.StartsAt });
        // A patient's appointments, upcoming and past: the chart's and the portal's lists.
        appointment.HasIndex(a => new { a.PatientId, a.StartsAt });
    }
}
