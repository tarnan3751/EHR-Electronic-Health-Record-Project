using Ehr.Data.Accounts;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ehr.Data.Orders;

// A clinician's acknowledgment that they have seen an order's results (the expansion plan's step 7): who and when,
// once for each order. PHI: row-level security is enabled and forced on it and every write is recorded by trigger
// (db/policies); reads go through the PHI reader in Ehr.Domain. Made by a clinician with the patient on their panel,
// for an order whose results are in. The database sets who and when. Never edited or deleted. Synthetic data only.
public class ResultAcknowledgment
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid OrderId { get; set; }

    // The order's patient, repeated here for row-level security and the audit.
    public Guid PatientId { get; set; }

    // Set by the database.
    public Guid AcknowledgedBy { get; set; }

    public DateTimeOffset AcknowledgedAt { get; set; }
}

// Maps ehr.result_acknowledgments. EhrDbContext picks this up with ApplyConfigurationsFromAssembly.
public sealed class ResultAcknowledgmentConfiguration : IEntityTypeConfiguration<ResultAcknowledgment>
{
    public void Configure(EntityTypeBuilder<ResultAcknowledgment> acknowledgment)
    {
        acknowledgment.ToTable("result_acknowledgments");
        acknowledgment.Property(a => a.AcknowledgedBy).HasDefaultValueSql("NULLIF(current_setting('app.user_id', true), '')::uuid");
        acknowledgment.Property(a => a.AcknowledgedAt).HasDefaultValueSql("now()");
        // Keyed on the patient too, so an acknowledgment can't be filed under another patient.
        acknowledgment.HasOne<Order>().WithMany()
            .HasForeignKey(a => new { a.OrderId, a.PatientId }).HasPrincipalKey(o => new { o.Id, o.PatientId })
            .OnDelete(DeleteBehavior.Restrict);
        acknowledgment.HasOne<StaffUser>().WithMany().HasForeignKey(a => a.AcknowledgedBy).OnDelete(DeleteBehavior.Restrict);
        // Once for each order.
        acknowledgment.HasIndex(a => a.OrderId).IsUnique();
        acknowledgment.HasIndex(a => a.PatientId);
    }
}
