namespace Ehr.Data.Orders;

// UC 1 Place an order (Tahseen Arnan): an order a clinician signed for a patient, a lab test, an imaging study, a
// medication or a referral, picked from the catalog (OrderCatalogItem), with the details its type asks for. PHI:
// row-level security is enabled and forced on it and every write is recorded by trigger (db/policies); reads go through
// the PHI reader in Ehr.Domain, which records them. A signed order is never edited in place: the one change the
// database allows is discontinuing an active order, once, with a reason, and it sets who and when itself. Changing an
// order signs a new one and discontinues the old one as replaced, each naming the other. Nothing deletes or reactivates
// an order. The database sets the signer and the signing time, and refuses a second active order for the same item
// without a reason (db/policies/60-orders.sql). Synthetic data only.
public class Order
{
    // UUIDv7, generated by whoever creates the row.
    public Guid Id { get; set; }

    public Guid PatientId { get; set; }

    // One of OrderType.
    public required string Type { get; set; }

    // The catalog item ordered, which is of the same type (a foreign key on both).
    public required string CatalogCode { get; set; }

    // The details the type asks for, as a JSON object of strings, such as {"dose": "500 mg"} (Ehr.Domain.Orders).
    public required string Details { get; set; }

    // One of OrderStatus: active when signed, revoked once discontinued.
    public required string Status { get; set; }

    // Set by the database: the signed-in user, the column's default, which row-level security holds it to; and the time
    // of the signing transaction, which a trigger sets whatever the client sent.
    public Guid SignerId { get; set; }

    public DateTimeOffset SignedAt { get; set; }

    // Why the clinician ordered an item the patient already had an active order for; null otherwise.
    public string? DuplicateReason { get; set; }

    // Ordering safety checks (step 8). What the database found against a medication order when it was signed (an
    // allergy, a drug of a class the patient is allergic to, an interaction with something they take), set by the
    // database; and why the clinician ordered it all the same, which the database requires when it found anything.
    // Both null for an order nothing was found against.
    public string? SafetyWarnings { get; set; }

    public string? SafetyOverrideReason { get; set; }

    // Discontinuing: why, and, set by the database, who and when. All three are null while the order is active.
    public string? DiscontinueReason { get; set; }

    public Guid? DiscontinuerId { get; set; }

    public DateTimeOffset? DiscontinuedAt { get; set; }

    // A change of an order is a new order: the order this one replaced, and, on that one, the order that replaced it.
    public Guid? ReplacesOrderId { get; set; }

    public Guid? ReplacedByOrderId { get; set; }
}

// What can be ordered. The codes are this app's own.
public static class OrderType
{
    public const string Lab = "lab";

    public const string Imaging = "imaging";

    public const string Medication = "medication";

    public const string Referral = "referral";

    public static readonly string[] All = [Lab, Imaging, Medication, Referral];
}

// FHIR R4's request status codes, the values Order.Status may hold. Two are written: active, and revoked, FHIR's code
// for a request that was stopped, which the screens call "Discontinued".
public static class OrderStatus
{
    public const string Draft = "draft";

    public const string Active = "active";

    public const string OnHold = "on-hold";

    public const string Revoked = "revoked";

    public const string Completed = "completed";

    public const string EnteredInError = "entered-in-error";

    public const string Unknown = "unknown";

    public static readonly string[] All = [Draft, Active, OnHold, Revoked, Completed, EnteredInError, Unknown];
}
